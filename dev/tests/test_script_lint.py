"""Lint every tracked extensionless shell and Python script, found by shebang.

treefmt lints `*.sh`, `*.bash`, and `*.py` by name. Scripts without an
extension are found here by their first line instead, wherever they move:
shellcheck (with the exclusions of nix/fmt.nix) for shell, `ruff check` and
`ruff format --check` for Python. A sourced shell file has no shebang; it names
its dialect with a `# shellcheck shell=bash` first line and is linted too.
"""

import importlib.machinery
import importlib.util
import os
import re
import subprocess
import tempfile
import unittest
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]

SHELL = "#!/usr/bin/env bash"
PYTHON = "#!/usr/bin/env python3.11"
SOURCED = "# shellcheck shell=bash"
# Scripts that keep another first line, and why.
OTHER_FORMS = {
    # Runs on a bare runner before any Nix shell (ci.yml).
    "dev/ci-select": "#!/usr/bin/env python3",
    # Runs before Nix exists, so it stays Bash 3.2 compatible.
    "dev/nix-up": "#!/bin/bash",
    # test-workspace.yml runs it on the runner before any Nix shell.
    "dev/check-ephemeral-backend": "#!/usr/bin/env python3",
}
# The Gradle wrapper scripts are generated by Gradle and updated with it.
VENDORED = {"apps/example-android/gradlew", "sdks/android/gradlew"}


def shellcheck_excludes():
    """The SC codes that treefmt passes to shellcheck in nix/fmt.nix."""
    text = (ROOT / "nix/fmt.nix").read_text()
    options = text.split("shellcheck.options", 1)[1].split("];", 1)[0]
    return re.findall(r"SC\d{4}", options)


def scripts(root=ROOT):
    """(path, kind, first line, git mode) of each extensionless script."""
    listing = subprocess.run(
        ["git", "ls-files", "-s", "-z"],
        cwd=root,
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    found = []
    for entry in filter(None, listing.split("\0")):
        meta, path = entry.split("\t", 1)
        mode = meta.split()[0]
        if mode == "120000" or path in VENDORED:
            continue
        if os.path.splitext(os.path.basename(path))[1]:
            continue
        file = root / path
        if not file.is_file():
            continue
        with file.open("rb") as stream:
            first = stream.readline(200).decode("utf-8", "replace").rstrip("\n")
        if first.startswith("#!") and "python" in first:
            found.append((path, "python", first, mode))
        elif first.startswith("#!") and re.search(r"\b(bash|sh)\b", first):
            found.append((path, "shell", first, mode))
        elif first == SOURCED:
            found.append((path, "shell", first, mode))
    return found


def lint(found, root=ROOT):
    """Return the failure messages of every check over `found`."""
    failures = []
    shell = [path for path, kind, _, _ in found if kind == "shell"]
    python = [path for path, kind, _, _ in found if kind == "python"]
    excludes = [arg for code in shellcheck_excludes() for arg in ("-e", code)]
    for command, files in (
        (["shellcheck", *excludes], shell),
        (["ruff", "check", "--no-cache"], python),
        (["ruff", "format", "--check", "--no-cache"], python),
    ):
        if not files:
            continue
        result = subprocess.run(
            [*command, *files], cwd=root, capture_output=True, text=True
        )
        if result.returncode:
            failures.append(
                f"{' '.join(command)} failed:\n{result.stdout}{result.stderr}"
            )
    for path, kind, first, mode in found:
        expected = OTHER_FORMS.get(path) or (SHELL if kind == "shell" else PYTHON)
        if first == SOURCED:
            continue
        if first != expected:
            failures.append(f"{path}: first line {first!r}, expected {expected!r}")
        if mode != "100755":
            failures.append(f"{path}: has a shebang but mode {mode[-3:]}, not 755")
    return failures


def script_lint_misses(paths):
    """The scripts whose change alone does not select test_dev."""
    loader = importlib.machinery.SourceFileLoader(
        "ci_select_for_lint", str(ROOT / "dev/ci-select")
    )
    selector = importlib.util.module_from_spec(
        importlib.util.spec_from_loader(loader.name, loader)
    )
    loader.exec_module(selector)
    payload = {
        "repository": {"full_name": "xmtp/libxmtp"},
        "pull_request": {
            "number": 1,
            "draft": False,
            "changed_files": 1,
            "head": {"sha": "head", "repo": {"full_name": "xmtp/libxmtp"}},
        },
    }
    return [
        path
        for path in paths
        if "test_dev"
        not in selector.select_suites(
            [path], "pull_request", payload, "success", 1, None, ()
        )["suites"]["test"]
    ]


def bare_runner_calls(paths, root=ROOT):
    """Workflow lines that run one of `paths` outside dev/nix-shell."""
    found = []
    files = sorted((root / ".github").glob("workflows/*.yml")) + sorted(
        (root / ".github").glob("actions/*/action.yml")
    )
    for file in files:
        data = yaml.safe_load(file.read_text()) or {}
        steps = [
            step
            for job in (data.get("jobs") or {}).values()
            for step in job.get("steps") or []
        ] + list((data.get("runs") or {}).get("steps") or [])
        for step in steps:
            run = step.get("run") or ""
            for path in paths:
                for match in re.finditer(
                    r"(?<![\w./-])" + re.escape(path) + r"(?![\w./-])", run
                ):
                    if "dev/nix-shell" not in run[: match.start()]:
                        found.append(f"{file.relative_to(root)}: {path}")
    return found


class ScriptLintTests(unittest.TestCase):
    def test_every_extensionless_script_passes(self):
        found = scripts()
        # Guards against a discovery change that finds nothing.
        self.assertGreater(len(found), 40, found)
        self.assertEqual(lint(found), [])

    def test_every_script_change_runs_the_script_lint(self):
        """A changed script selects test_dev, which runs this test."""
        self.assertEqual(script_lint_misses([path for path, *_ in scripts()]), [])

    def test_python311_scripts_run_inside_the_nix_shell(self):
        """A bare runner has no python3.11; such scripts run in dev/nix-shell."""
        python311 = [path for path, _, first, _ in scripts() if first == PYTHON]
        self.assertGreater(len(python311), 3)
        self.assertEqual(bare_runner_calls(python311), [])

    def test_planted_findings_fail(self):
        """A planted script of each kind fails its linter, mode, or form."""
        with tempfile.TemporaryDirectory() as folder:
            root = Path(folder)
            subprocess.run(["git", "init", "--quiet", str(root)], check=True)
            files = {
                # SC2034: an unused variable (SC2086 is excluded on purpose).
                "unused": SHELL + "\nvalue=1\n",
                # F401: an unused import.
                "tool": PYTHON + "\nimport os\n",
                "plain": "#!/bin/bash\necho fine\n",
            }
            for name, text in files.items():
                (root / name).write_text(text)
                (root / name).chmod(0o755)
            (root / "plain").chmod(0o644)
            subprocess.run(["git", "add", "."], cwd=root, check=True)
            found = scripts(root)
            self.assertEqual(sorted(path for path, *_ in found), sorted(files))
            failures = "\n".join(lint(found, root))
            self.assertIn("SC2034", failures)
            self.assertIn("F401", failures)
            self.assertIn("plain: first line '#!/bin/bash'", failures)
            self.assertIn("plain: has a shebang but mode 644", failures)


if __name__ == "__main__":
    unittest.main()
