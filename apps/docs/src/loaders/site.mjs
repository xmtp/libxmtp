import { readdir, readFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { basename, dirname } from "node:path";
import { docsLoader } from "@astrojs/starlight/loaders";
import { prepareDocument } from "./prepare.mjs";

// The approved and draft specs live in specs/ at the repository root and are
// published under /specs/. The superseded documents in docs/specs/ stay
// published under /specs/legacy/ until each one is deleted with its
// replacement.
const SPEC_SOURCES = [
  {
    dir: "../../specs/",
    editBase: "https://github.com/xmtp/libxmtp/edit/main/specs/",
    route(name) {
      if (name === "README.md") return "/specs/";
      return `/specs/${name.replace(/\.md$/u, "").toLowerCase()}/`;
    },
    order(name) {
      const fixed = {
        "README.md": 0,
        "SPEC-spec-format.md": 1,
        "GLOSSARY.md": 2,
        "PREFIXES.md": 3,
      };
      return fixed[name] ?? 10;
    },
  },
  {
    dir: "../../docs/specs/",
    editBase: "https://github.com/xmtp/libxmtp/edit/main/docs/specs/",
    route(name) {
      return `/specs/legacy/${name.replace(/\.md$/u, "").replaceAll("_", "-")}/`;
    },
    // Keep the numeric order of the legacy files, after every current spec.
    order(name) {
      return 100 + Number(name.match(/^\d+/u)?.[0] ?? 99);
    },
  },
];

const BADGES = {
  draft: { text: "Draft", variant: "caution" },
  legacy: { text: "Legacy", variant: "note" },
};

function idForRoute(route) {
  const id = route.replace(/^\/|\/$/gu, "");
  return id === "specs" ? "specs/index" : id;
}

export function siteLoader() {
  return {
    name: "xmtp-docs",
    async load(context) {
      await docsLoader().load(context);
      const sources = SPEC_SOURCES.map((source) => ({
        ...source,
        url: new URL(source.dir, context.config.root),
      }));
      const glossary = new URL(
        "../../docs/error_glossary.md",
        context.config.root,
      );
      async function loadFile(input) {
        const { url, id, source } = input;
        const filename = url.pathname.split("/").at(-1);
        const resolveLink = source
          ? (target) =>
              names.get(source).has(target) ? source.route(target) : undefined
          : undefined;
        const { title, body, order, status } = prepareDocument(
          await readFile(url, "utf8"),
          filename,
          { spec: Boolean(source), resolveLink },
        );
        // Starlight places an entry in the autogenerated sidebar by its path
        // under src/content/docs, so the stored path is the route's virtual
        // file. The real path is kept for schema errors.
        const filePath = `src/content/docs/${id}.md`;
        const sidebar = { order: source?.order?.(filename) ?? order };
        if (BADGES[status]) sidebar.badge = BADGES[status];
        const data = await context.parseData({
          id,
          filePath: fileURLToPath(url),
          data: {
            title,
            sidebar,
            editUrl: source
              ? `${source.editBase}${filename}`
              : `https://github.com/xmtp/libxmtp/edit/main/docs/${filename}`,
          },
        });
        // Rendering uses the route ID; source metadata keeps the real file path.
        const renderURL = new URL(
          `src/content/docs/${id}.md`,
          context.config.root,
        );
        context.store.set({
          id,
          data,
          body,
          filePath,
          digest: context.generateDigest(body),
          rendered: await context.renderMarkdown(body, { fileURL: renderURL }),
        });
      }
      // A relative link in a spec names a sibling file. Only a link into the
      // same directory resolves; anything else stays as written.
      const names = new Map();
      for (const source of sources)
        names.set(
          source,
          new Set(
            (await readdir(source.url)).filter((name) => name.endsWith(".md")),
          ),
        );
      function inputFor(source, name) {
        return {
          url: new URL(name, source.url),
          id: idForRoute(source.route(name)),
          source,
        };
      }
      const inputs = [];
      for (const source of sources)
        for (const name of [...names.get(source)].sort())
          inputs.push(inputFor(source, name));
      const glossaryInput = {
        url: glossary,
        id: "reference/error-glossary",
        source: undefined,
      };
      inputs.push(glossaryInput);
      for (const input of inputs) await loadFile(input);
      if (context.watcher) {
        const dirs = new Map(
          sources.map((source) => [
            fileURLToPath(source.url).replace(/\/$/u, ""),
            source,
          ]),
        );
        context.watcher.add([...dirs.keys(), fileURLToPath(glossary)]);
        function inputForPath(path) {
          if (path === fileURLToPath(glossary)) return glossaryInput;
          const source = dirs.get(dirname(path));
          if (!source || !path.endsWith(".md")) return;
          const name = basename(path);
          names.get(source).add(name);
          return inputFor(source, name);
        }
        async function update(path) {
          const input = inputForPath(path);
          if (input) await loadFile(input);
        }
        context.watcher.on("add", update);
        context.watcher.on("change", update);
        context.watcher.on("unlink", (path) => {
          const input = inputForPath(path);
          if (input) {
            names.get(input.source)?.delete(basename(path));
            context.store.delete(input.id);
          }
        });
      }
    },
  };
}
