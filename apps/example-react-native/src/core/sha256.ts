const H0 = [
  0x6a09e667, 0xbb67ae85, 0x3c6ef372, 0xa54ff53a, 0x510e527f, 0x9b05688c,
  0x1f83d9ab, 0x5be0cd19,
];

const rotr = (value: number, bits: number): number =>
  (value >>> bits) | (value << (32 - bits));

/** The SHA-256 digest of `bytes` (32 bytes). */
export function sha256(bytes: Uint8Array): Uint8Array {
  // Padding: 0x80, zeros, then the bit length as a 64-bit big-endian number.
  const blocks = Math.ceil((bytes.length + 9) / 64);
  const message = new Uint8Array(blocks * 64);
  message.set(bytes);
  message[bytes.length] = 0x80;
  const view = new DataView(message.buffer);
  const bits = bytes.length * 8;
  view.setUint32(message.length - 8, Math.floor(bits / 0x1_0000_0000));
  view.setUint32(message.length - 4, bits >>> 0);

  const hash = [...H0];
  const w = new Uint32Array(64);
  for (let block = 0; block < blocks; block += 1) {
    for (let t = 0; t < 16; t += 1) w[t] = view.getUint32(block * 64 + t * 4);
    for (let t = 16; t < 64; t += 1) {
      const a = w[t - 15];
      const b = w[t - 2];
      const s0 = rotr(a, 7) ^ rotr(a, 18) ^ (a >>> 3);
      const s1 = rotr(b, 17) ^ rotr(b, 19) ^ (b >>> 10);
      w[t] = (w[t - 16] + s0 + w[t - 7] + s1) >>> 0;
    }
    let [a, b, c, d, e, f, g, h] = hash;
    for (let t = 0; t < 64; t += 1) {
      const s1 = rotr(e, 6) ^ rotr(e, 11) ^ rotr(e, 25);
      const choice = (e & f) ^ (~e & g);
      const t1 = (h + s1 + choice + K[t] + w[t]) >>> 0;
      const s0 = rotr(a, 2) ^ rotr(a, 13) ^ rotr(a, 22);
      const majority = (a & b) ^ (a & c) ^ (b & c);
      const t2 = (s0 + majority) >>> 0;
      h = g;
      g = f;
      f = e;
      e = (d + t1) >>> 0;
      d = c;
      c = b;
      b = a;
      a = (t1 + t2) >>> 0;
    }
    hash[0] = (hash[0] + a) >>> 0;
    hash[1] = (hash[1] + b) >>> 0;
    hash[2] = (hash[2] + c) >>> 0;
    hash[3] = (hash[3] + d) >>> 0;
    hash[4] = (hash[4] + e) >>> 0;
    hash[5] = (hash[5] + f) >>> 0;
    hash[6] = (hash[6] + g) >>> 0;
    hash[7] = (hash[7] + h) >>> 0;
  }

  const digest = new Uint8Array(32);
  const out = new DataView(digest.buffer);
  hash.forEach((word, index) => out.setUint32(index * 4, word));
  return digest;
}

/** UTF-8 bytes of `text`. Hermes and Node both provide `TextEncoder`. */
export function utf8(text: string): Uint8Array {
  return new TextEncoder().encode(text);
}
